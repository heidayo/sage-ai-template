  else
    echo "  WARN: No sha256 command found. Skipping install-state generation."
    return
  fi

  cat > "$state_file" <<STATEHEADER
version: "${SAGE_VERSION}"
installed_at: "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
files:
