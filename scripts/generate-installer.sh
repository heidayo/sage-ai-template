# ファイルを heredoc として埋め込む関数
embed_file() {
  local var_name="$1"
  local file_path="$2"
  local delimiter="__EOF_${var_name}__"

  if [ ! -f "$file_path" ]; then
    echo "WARN: $file_path not found, skipping" >&2
    echo "${var_name}=''"
    return
  fi

  echo "read -r -d '' ${var_name} <<'${delimiter}' || true"
  cat "$file_path"
  echo ""
  echo "${delimiter}"
}

